export const WHATSAPP_PHONE = '+967781282285';

export function getWhatsAppUrl(customMessage?: string): string {
  const cleanPhone = WHATSAPP_PHONE.replace(/[^0-9]/g, '');
  const text =
    customMessage ||
    'Hello IT EXPERTS — THE PROOF ROOM! I would like to discuss a technical or academic project and request a Free Initial Tech Check.';
  return `https://wa.me/${cleanPhone}?text=${encodeURIComponent(text)}`;
}

